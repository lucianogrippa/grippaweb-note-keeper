use crate::entities::categories::Category;
use anyhow::Context;


pub async fn get_categories_by_user_id(
    user_id: &str,
     pool: &sqlx::Pool<sqlx::Sqlite>,
) -> Result<Vec<Category>, anyhow::Error> {
    let categories = sqlx::query_as::<_, Category>(
        "SELECT id, user_id, name, description, created_at, updated_at FROM categories WHERE user_id = ? ORDER BY name ASC",
    )
    .bind(user_id)
    .fetch_all(pool)
    .await
    .context("Failed to retrieve categories from database")?;

    Ok(categories)
}


pub async fn find_by_name_or_description(
    user_id: &str,
    keyword: &str,
    pool: &sqlx::Pool<sqlx::Sqlite>,
) -> Result<Vec<Category>, anyhow::Error> {
    let like_pattern = format!("%{}%", keyword);
    let categories = sqlx::query_as::<_, Category>(
        "SELECT id, user_id, name, description, created_at, updated_at FROM categories WHERE user_id = ? AND (name LIKE ? OR description LIKE ?) ORDER BY name ASC",
    )
    .bind(user_id)
    .bind(&like_pattern)
    .bind(&like_pattern)
    .fetch_all(pool)
    .await
    .context("Failed to search categories in database")?;

    Ok(categories)
}

pub async fn get_category_by_id(
    category_id: &str,
     pool: &sqlx::Pool<sqlx::Sqlite>,
) -> Result<Category, anyhow::Error> {
    let category = sqlx::query_as::<_, Category>(
        "SELECT id, user_id, name, description, created_at, updated_at FROM categories WHERE id = ? ORDER BY name ASC",
    )
    .bind(category_id)
    .fetch_one(pool)
    .await
    .context("Failed to retrieve category from database")?;

    Ok(category)
}

/**
 * Add new categories and return the new category ID. The category ID is generated by the database as an auto-incrementing integer, so we can retrieve it after the insert operation using `last_insert_rowid()`.
 */
pub async fn new_category(
    user_id: &str,
    name: &str,
    description: Option<&str>,
    pool: &sqlx::Pool<sqlx::Sqlite>,
) -> Result<String, anyhow::Error> {

    let result   = 
    sqlx::query(
        "INSERT INTO categories (user_id, name, description, created_at, updated_at) VALUES (?, ?, ?, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)",
    )
    .bind(user_id)
    .bind(name)
    .bind(description)
    .execute(pool)
    .await
    .context("Failed to insert new category into database")?;

    match result.last_insert_rowid() {
        id if id > 0 => Ok(id.to_string()),
        _ => Err(anyhow::anyhow!("Failed to retrieve new category ID")),
    }
}


pub async fn edit_category(
    category_id: &str,
    name: Option<&str>,
    description: Option<&str>,
    pool: &sqlx::Pool<sqlx::Sqlite>,
) -> Result<(), anyhow::Error> {
    if name.is_none() && description.is_none() {
        return Ok(());
    }

    if let (Some(name), Some(description)) = (name, description) {
        sqlx::query("UPDATE categories SET name = ?, description = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?")
            .bind(name)
            .bind(description)
            .bind(category_id)
            .execute(pool)
            .await
            .context("Failed to edit category in database")?;
    } else if let Some(name) = name {
        sqlx::query("UPDATE categories SET name = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?")
            .bind(name)
            .bind(category_id)
            .execute(pool)
            .await
            .context("Failed to edit category in database")?;
    } else if let Some(description) = description {
        sqlx::query("UPDATE categories SET description = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?")
            .bind(description)
            .bind(category_id)
            .execute(pool)
            .await
            .context("Failed to edit category in database")?;
    }

    Ok(())
}

pub async fn delete_category(
    category_id: &str,
    pool: &sqlx::Pool<sqlx::Sqlite>,
) -> Result<(), anyhow::Error> {
    sqlx::query("DELETE FROM categories WHERE id = ?")
        .bind(category_id)
        .execute(pool)
        .await
        .context("Failed to delete category from database")?;

    Ok(())
}