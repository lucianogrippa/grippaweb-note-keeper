use crate::{entities::categories::Group};
use anyhow::{Context, Result};


pub async fn get_groups_by_category_id(
    categories_id: &str,
    pool: &sqlx::Pool<sqlx::Sqlite>,
) -> Result<Vec<Group>, anyhow::Error> {

    let groups = sqlx::query_as::<_, Group>(
            "SELECT groups.id, groups.categories_id, groups.name, categories.name as category_name, groups.created_at, groups.updated_at FROM groups join categories ON groups.categories_id = categories.id WHERE categories_id = ? ORDER BY groups.name ASC",
        )
        .bind(categories_id)
        .fetch_all(pool)
        .await?;

    Ok(groups)
}

pub async fn get_group_by_id(
    group_id: &str,
    pool: &sqlx::Pool<sqlx::Sqlite>,
) -> Result<Group, anyhow::Error> {
    let group = sqlx::query_as::<_, Group>(
            "SELECT groups.id, groups.categories_id, groups.name, categories.name as category_name, groups.created_at, groups.updated_at FROM groups join categories ON groups.categories_id = categories.id WHERE groups.id = ?",
        )
        .bind(group_id)
        .fetch_one(pool)
        .await?;

    Ok(group)
}

/**
 * Add new groups and return the new group ID. The group ID is generated by the database as an auto-incrementing integer, so we can retrieve it after the insert operation using `last_insert_rowid()`.
 */
pub async fn new_group(
    categories_id: &str,
    name: &str,
    pool: &sqlx::Pool<sqlx::Sqlite>,
) -> Result<i64, anyhow::Error> {
    let result = sqlx::query("INSERT INTO groups (categories_id, name, created_at, updated_at) VALUES (?, ?, datetime('now'), datetime('now'))")
        .bind(categories_id)
        .bind(name)
        .execute(pool)
        .await?;

    let new_group_id = result.last_insert_rowid();

    Ok(new_group_id)
}

pub async fn edit_group(
    group_id: &str,
    name: &str,
    pool: &sqlx::Pool<sqlx::Sqlite>,
) -> Result<(), anyhow::Error> {

    sqlx::query("UPDATE groups SET name = ?, updated_at = datetime('now') WHERE id = ?")
        .bind(name)
        .bind(group_id)
        .execute(pool)
        .await?;

    Ok(())
}

pub async fn delete_group(
    group_id: &str,
    pool: &sqlx::Pool<sqlx::Sqlite>,
) -> Result<(), anyhow::Error> {

    sqlx::query("DELETE FROM groups WHERE id = ?")
        .bind(group_id)
        .execute(pool)
        .await
        .context("Failed to delete group from database")?;

    Ok(())
}